class FusionEngine:
    """Thin wrapper around the project's real SensorFusionEngine."""

    def __init__(self):
        from sensor_fusion.fusion_engine import (
            SensorFusionEngine, SensorReading
        )
        self._engine  = SensorFusionEngine()
        self._Reading = SensorReading
        self._history: deque = deque(maxlen=60)

    def fuse(self, rf: dict, audio: dict, visual: dict) -> dict:
        rf_r = self._Reading(
            sensor_type="RF", active=True,
            detection_present=(rf["class"] != "BACKGROUND"),
            raw_score=rf["score"], confidence=rf["confidence"],
            class_name=rf["class"],
        )
        au_r = self._Reading(
            sensor_type="AUDIO", active=True,
            detection_present=(audio["class"] != "BACKGROUND"),
            raw_score=audio["score"], confidence=audio["confidence"],
            class_name=audio["class"],
        )
        vis_r = self._Reading(
            sensor_type="VISUAL", active=True,
            detection_present=(visual["n_tracks"] > 0),
            raw_score=visual["score"], confidence=min(1.0, visual["score"]*1.3+0.1),
            class_name="VISUAL_TRACK" if visual["n_tracks"] > 0 else "BACKGROUND",
            extra={"n_tracks": visual["n_tracks"]},
        )
        assessment = self._engine.fuse(rf_r, au_r, vis_r)
        self._history.append(assessment.fused_score)
        return {
            "fused_score":       round(assessment.fused_score, 4),
            "threat_level":      assessment.threat_level.value,
            "threat_color":      assessment.threat_color,
            "is_alarm":          assessment.is_alarm,
            "alarm_count":       self._engine._alarm_count,
            "sensor_agreement":  round(assessment.sensor_agreement, 3),
            "alert_message":     assessment.alert_message,
            "recommended_action":assessment.recommended_action,
            "history":           list(self._history),
        }


