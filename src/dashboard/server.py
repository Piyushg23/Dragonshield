async def _main_loop():
    """
    Real inference loop.
    RF:     runs every tick via executor (I/O-bound IQ processing)
    Audio:  reads latest from background thread (runs continuously)
    Visual: reads latest from background thread (runs continuously)
    Fusion: runs every tick with latest sensor readings
    Video:  sends JPEG every other tick (~10-15 fps over WS)
    Telemetry: sends JSON every 0.5s
    """
    global _last_telemetry
    tick = 0
    last_telem_t = 0.0
    loop = asyncio.get_event_loop()

    while _running:
        t0 = time.perf_counter()

        # ── RF (run in executor — CPU-bound feature extraction + classifier)
        rf_result = await loop.run_in_executor(None, _RF.read)

        # ── Audio (background thread, just read latest)
        audio_result = _AUDIO.read()

        # ── Visual (background thread, just read latest + get annotated frame)
        vis_result, annotated_frame = _VISUAL.read()

        # ── Fuse
        fused = _FUSION.fuse(rf_result, audio_result, vis_result)

        # ── Broadcast to clients
        if _clients:
            tick += 1

            # Video frame — every 2nd tick
            if annotated_frame is not None and tick % 2 == 0:
                try:
                    _, buf = cv2.imencode(".jpg", annotated_frame,
                                         [cv2.IMWRITE_JPEG_QUALITY, 70])
                    b64 = base64.b64encode(buf.tobytes()).decode()
                    await _broadcast(json.dumps({"type": "frame", "data": b64}))
                except Exception as e:
                    log.debug(f"Frame encode error: {e}")

            # Telemetry every 500ms
            now = time.perf_counter()
            if now - last_telem_t >= 0.5:
                last_telem_t = now
                telem = {
                    "timestamp": round(time.time(), 3),
                    "uptime_s":  round(time.time() - _session_start, 1),

                    # Fused result
                    **fused,

                    # Per-sensor raw
                    "rf":    {**rf_result,    "active": True},
                    "audio": {**audio_result, "active": True},
                    "visual":{**vis_result,   "active": True},

                    # System meta
                    "meta": {
                        "camera_active":     _VISUAL.camera_active,
                        "rf_hardware":       _RF.hardware,
                        "audio_hardware":    _AUDIO.hardware,
                        "yolo":              _VISUAL.yolo is not None,
                        "real_rf_model":     True,
                        "real_audio_model":  True,
                        "clients":           len(_clients),
                    }
                }
                _last_telemetry = telem
                await _broadcast(
                            json.dumps({"type": "telemetry", "data": telem}, default=str)
                )

        elapsed = time.perf_counter() - t0
        await asyncio.sleep(max(0.0, 0.05 - elapsed))   # ~20 Hz


