class RFSensor:
    """
    Wraps the trained RFDroneClassifier.
    Reads from RTL-SDR if present, otherwise generates realistic IQ frames
    via SyntheticRFDataGenerator — identical distribution to training data,
    so the classifier output is as real as it gets without hardware.
    """
    BANDS_MHZ = [2412, 2437, 2462, 5745, 5785]

    def __init__(self, model_path: str):
        from rf_classifier.rf_classifier import (
            RFDroneClassifier, SyntheticRFDataGenerator,
            RTLSDRInterface, DRONE_CLASSES, THREAT_LEVELS
        )
        self.clf = RFDroneClassifier(model_path=model_path)
        self.gen = SyntheticRFDataGenerator()
        self.DRONE_CLASSES = DRONE_CLASSES
        self.THREAT_LEVELS = THREAT_LEVELS
        self.sdr: Optional[RTLSDRInterface] = None
        self.hardware = False
        self._spectrum_buf: List[float] = []
        self._freq_buf: List[int] = []
        self._try_hardware()

    def _try_hardware(self):
        try:
            from rf_classifier.rf_classifier import RTLSDRInterface
            sdr = RTLSDRInterface()
            if sdr.sdr is not None:
                self.sdr = sdr
                self.hardware = True
                log.info("✓ RTL-SDR hardware connected")
            else:
                log.info("RTL-SDR not found — RF running on trained model + synthetic IQ")
        except Exception:
            log.info("RTL-SDR not available — RF running on trained model + synthetic IQ")

    def read(self) -> dict:
        """Read one RF frame, classify with trained model, return full result."""
        if self.hardware and self.sdr:
            # Real hardware: sweep bands, pick highest-energy band
            band_powers = self.sdr.sweep_bands(self.BANDS_MHZ)
            best_band = max(band_powers, key=band_powers.get)
            self.sdr.sdr.center_freq = best_band * 1e6
            iq = self.sdr.read_samples(1024)
            freq_mhz = float(best_band)
            signal_dbm = float(band_powers[best_band])
        else:
            # No hardware: sample from the same distribution the model was trained on
            # We don't pick a random class — we sample uniformly across ALL classes
            # so the classifier has to actually work to discriminate.
            cls_idx = int(np.random.choice(list(self.DRONE_CLASSES.keys())))
            iq = self.gen.generate(cls_idx, n_frames=1)[0]
            freq_mhz = float(np.random.choice(self.BANDS_MHZ))
            signal_dbm = float(-90 + np.random.uniform(0, 40))

        detection = self.clf.predict(iq, center_freq_mhz=freq_mhz,
                                     signal_strength_dbm=signal_dbm)

        # Build 55-bin spectrum from real IQ
        from scipy.fft import fft
        fft_mag = np.abs(fft(iq, n=110))[:55]
        fft_db  = 10 * np.log10(fft_mag**2 + 1e-10)
        spectrum = fft_db.tolist()
        freqs    = list(range(int(freq_mhz - 54), int(freq_mhz + 56), 2))[:55]

        return {
            "hardware": self.hardware,
            "score":        float(detection.threat_score),
            "confidence":   float(detection.confidence),
            "class":        detection.class_name,
            "freq_mhz":     freq_mhz,
            "signal_dbm":   signal_dbm,
            "hopping":      detection.frequency_hopping,
            "threat_level": detection.threat_level,
            "spectrum":     [round(v, 1) for v in spectrum],
            "freqs":        freqs,
        }


