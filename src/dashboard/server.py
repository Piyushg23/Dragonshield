class AudioSensor:
    """
    Wraps the trained AcousticDroneClassifier.
    Live mic → classify continuously in a background thread.
    Latest result available via self.latest.
    """

    def __init__(self, model_path: str):
        from audio_classifier.audio_classifier import (
            AcousticDroneClassifier, MicrophoneStream, AUDIO_CLASSES, AUDIO_THREAT
        )
        self.clf = AcousticDroneClassifier(model_path=model_path)
        self.AUDIO_CLASSES = AUDIO_CLASSES
        self.AUDIO_THREAT  = AUDIO_THREAT
        self.mic = MicrophoneStream()
        self.hardware = self.mic.stream is not None
        self.latest: dict = {"score": 0.0, "confidence": 0.0, "class": "BACKGROUND",
                             "freq_hz": 0.0, "rpm": 0.0, "n_rotors": 4, "snr_db": 0.0,
                             "hardware": self.hardware}
        self._lock = threading.Lock()
        self._running = True
        t = threading.Thread(target=self._loop, daemon=True)
        t.start()
        if self.hardware:
            log.info("✓ Microphone connected — live acoustic classification active")
        else:
            log.info("Microphone not found — Audio running on trained model + synthetic audio")

    def _loop(self):
        while self._running:
            audio = self.mic.read_frame(timeout=2.0)
            if audio is None:
                time.sleep(0.1)
                continue
            try:
                det = self.clf.predict(audio)
                result = {
                    "hardware":   self.hardware,
                    "score":      float(det.threat_score),
                    "confidence": float(det.confidence),
                    "class":      det.class_name,
                    "freq_hz":    float(det.dominant_freq_hz),
                    "rpm":        float(det.estimated_rpm),
                    "n_rotors":   int(det.n_rotors_estimate),
                    "snr_db":     float(det.snr_db),
                }
                with self._lock:
                    self.latest = result
            except Exception as e:
                log.debug(f"Audio classify error: {e}")
            time.sleep(0.05)

    def read(self) -> dict:
        with self._lock:
            return dict(self.latest)

    def stop(self):
        self._running = False
        self.mic.stop()


