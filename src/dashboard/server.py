class _StandaloneProcessor:
    """Lightweight MOG2 + Kalman processor for uploaded video frames."""
    def __init__(self):
        self.bg = cv2.createBackgroundSubtractorMOG2(history=250, varThreshold=38, detectShadows=False)
        self.morph_k = cv2.getStructuringElement(cv2.MORPH_ELLIPSE, (5, 5))
        self._tracks: Dict[int, dict] = {}
        self._next_id = 0
        self._frame_count = 0
        self._fps_buf = []
        self._t_last = time.perf_counter()

    def reset(self):
        """Call when switching to a new video."""
        self.bg = cv2.createBackgroundSubtractorMOG2(history=250, varThreshold=38, detectShadows=False)
        self._tracks = {}
        self._next_id = 0
        self._frame_count = 0

    def process(self, frame: np.ndarray) -> dict:
        """Run detection on one frame, return result dict + annotated JPEG b64."""
        self._frame_count += 1

        # Detect
        fg = self.bg.apply(frame)
        fg = cv2.morphologyEx(fg, cv2.MORPH_OPEN, self.morph_k)
        fg = cv2.dilate(fg, self.morph_k, iterations=2)
        cnts, _ = cv2.findContours(fg, cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_SIMPLE)
        detections = []
        h, w = frame.shape[:2]
        for c in cnts:
            area = cv2.contourArea(c)
            if 100 < area < 60000:
                x, y, bw, bh = cv2.boundingRect(c)
                asp = bw / max(bh, 1)
                if 0.18 < asp < 5.5 and bw < w*0.55 and bh < h*0.55:
                    detections.append({
                        "cx": x+bw/2, "cy": y+bh/2,
                        "x1": float(x), "y1": float(y),
                        "x2": float(x+bw), "y2": float(y+bh),
                        "w": float(bw), "h": float(bh),
                        "conf": min(0.94, area/8000*0.7+0.25),
                    })

        # Warmup: first 8 frames just build background model
        if self._frame_count <= 8:
            return {"tracks": [], "n_tracks": 0, "visual_score": 0.0,
                    "fps": 0.0, "frame_b64": _encode_frame(frame), "detector": "mog2_warmup"}

        tracks = self._kalman_update(detections)
        vis_score = max((t["threat"] for t in tracks), default=0.0)
        if len(tracks) > 1:
            vis_score = min(1.0, vis_score + (len(tracks)-1)*0.05)

        annotated = self._annotate(frame.copy(), tracks, vis_score)

        # FPS
        now = time.perf_counter()
        self._fps_buf.append(now)
        while self._fps_buf and now - self._fps_buf[0] > 2.0:
            self._fps_buf.pop(0)
        fps = len(self._fps_buf) / max(now - self._fps_buf[0], 1e-3) if len(self._fps_buf) > 1 else 0.0

        return {
            "tracks": tracks,
            "n_tracks": len(tracks),
            "visual_score": round(vis_score, 4),
            "fps": round(fps, 1),
            "frame_b64": _encode_frame(annotated),
            "detector": "mog2+kalman",
        }

    def _kalman_update(self, detections):
        # Predict
        for t in self._tracks.values():
            self._kf_predict(t)
        # Greedy match
        tids = list(self._tracks.keys())
        used_t, used_d = set(), set()
        matched = {}
        if tids and detections:
            cost = np.zeros((len(tids), len(detections)))
            for ti, tid in enumerate(tids):
                px, py = self._tracks[tid]["pos"]
                for di, d in enumerate(detections):
                    cost[ti, di] = math.hypot(px-d["cx"], py-d["cy"])
            for idx in np.argsort(cost, axis=None):
                ti, di = divmod(int(idx), len(detections))
                if ti in used_t or di in used_d: continue
                if cost[ti, di] > 110: break
                matched[tids[ti]] = detections[di]
                used_t.add(ti); used_d.add(di)
        # Update matched
        for tid, det in matched.items():
            self._kf_update(self._tracks[tid], det["cx"], det["cy"])
            self._tracks[tid].update({"box": det, "gone": 0, "frames": self._tracks[tid]["frames"]+1})
            pos = self._tracks[tid]["pos"]
            self._tracks[tid]["traj"].append((round(pos[0],1), round(pos[1],1)))
            if len(self._tracks[tid]["traj"]) > 40: self._tracks[tid]["traj"].pop(0)
        # New
        for di, det in enumerate(detections):
            if di in used_d: continue
            nid = self._next_id; self._next_id += 1
            self._tracks[nid] = {
                "state": np.array([det["cx"],det["cy"],0.,0.]),
                "P": np.eye(4)*10., "box": det, "gone": 0, "frames": 1,
                "traj": [(det["cx"],det["cy"])], "pos": (det["cx"],det["cy"]),
                "vel": (0.,0.),
            }
        # Age
        for ti, tid in enumerate(tids):
            if ti not in used_t: self._tracks[tid]["gone"] += 1
        self._tracks = {tid: t for tid, t in self._tracks.items() if t["gone"] <= 18}
        # Output
        out = []
        for tid, t in self._tracks.items():
            if t["gone"] > 0: continue
            pos = t["pos"]; vel = t["vel"]; box = t["box"]
            dist_m = max(4, (0.3*800)/max(box["w"],1))
            spd = math.hypot(*vel)
            threat = min(1.0, 10.0/max(dist_m,1)*0.6 + box["conf"]*0.4)
            out.append({
                "id": tid,
                "x1":int(box["x1"]),"y1":int(box["y1"]),"x2":int(box["x2"]),"y2":int(box["y2"]),
                "cx":round(pos[0],1),"cy":round(pos[1],1),
                "vx":round(vel[0],2),"vy":round(vel[1],2),
                "heading": round((math.degrees(math.atan2(vel[1],vel[0]))+360)%360, 1),
                "distance_m": round(dist_m,1),
                "confidence": round(box["conf"],3),
                "threat": round(threat,3),
                "frames": t["frames"],
                "traj": [[p[0],p[1]] for p in t["traj"]],
            })
        return out

    @staticmethod
    def _kf_predict(t):
        F = np.array([[1,0,1,0],[0,1,0,1],[0,0,1,0],[0,0,0,1]],dtype=np.float64)
        Q = np.diag([1.,1.,4.,4.])
        t["state"] = F @ t["state"]
        t["P"] = F @ t["P"] @ F.T + Q
        t["pos"] = (float(t["state"][0]), float(t["state"][1]))
        t["vel"] = (float(t["state"][2]), float(t["state"][3]))

    @staticmethod
    def _kf_update(t, mx, my):
        H = np.array([[1,0,0,0],[0,1,0,0]],dtype=np.float64)
        R = np.eye(2)*4.
        z = np.array([mx,my])
        y = z - H @ t["state"]
        S = H @ t["P"] @ H.T + R
        K = t["P"] @ H.T @ np.linalg.inv(S)
        t["state"] = t["state"] + K @ y
        t["P"] = (np.eye(4) - K @ H) @ t["P"]
        t["pos"] = (float(t["state"][0]), float(t["state"][1]))
        t["vel"] = (float(t["state"][2]), float(t["state"][3]))

    def _annotate(self, frame, tracks, vis_score):
        """Minimal, clean annotation — tight corner-tick box + one label line per track."""
        h, w = frame.shape[:2]

        def threat_color(thr):
            if thr < 0.35: return (0, 220, 100)
            if thr < 0.65: return (0, 190, 255)
            if thr < 0.85: return (30, 130, 255)
            return (40, 40, 255)

        for t in tracks:
            c   = threat_color(t["threat"])
            x1, y1, x2, y2 = t["x1"], t["y1"], t["x2"], t["y2"]
            bw  = max(1, x2 - x1)

            # subtle dim box outline
            cv2.rectangle(frame, (x1, y1), (x2, y2), tuple(v//3 for v in c), 1)
            # corner ticks only
            tk = min(8, bw // 4)
            for ox, oy, dx, dy in [
                (x1, y1, tk, 0), (x1, y1, 0, tk),
                (x2, y1, -tk, 0), (x2, y1, 0, tk),
                (x1, y2, tk, 0), (x1, y2, 0, -tk),
                (x2, y2, -tk, 0), (x2, y2, 0, -tk),
            ]:
                cv2.line(frame, (ox, oy), (ox+dx, oy+dy), c, 2)

            # one compact label above box with dark backing
            label = f"T{t['id']}  {int(t['confidence']*100)}%  {t['distance_m']:.0f}m  {t['threat']*100:.0f}%thr"
            lx = max(0, x1)
            ly = max(14, y1 - 5)
            (tw, th), _ = cv2.getTextSize(label, cv2.FONT_HERSHEY_SIMPLEX, 0.36, 1)
            cv2.rectangle(frame, (lx - 1, ly - th - 2), (lx + tw + 1, ly + 1), (5, 10, 18), -1)
            cv2.putText(frame, label, (lx, ly), cv2.FONT_HERSHEY_SIMPLEX, 0.36, c, 1, cv2.LINE_AA)

        # minimal status bar bottom 20px
        lvl = ("CLEAR" if vis_score < 0.10 else
               "LOW"   if vis_score < 0.35 else
               "MEDIUM"if vis_score < 0.60 else
               "HIGH"  if vis_score < 0.80 else "CRITICAL")
        lcol = threat_color(vis_score)
        overlay = frame.copy()
        cv2.rectangle(overlay, (0, h - 20), (w, h), (4, 8, 16), -1)
        cv2.addWeighted(overlay, 0.75, frame, 0.25, 0, frame)
        cv2.putText(frame, f"[{lvl}]  {len(tracks)} TRK  {vis_score*100:.0f}%",
                    (6, h - 5), cv2.FONT_HERSHEY_SIMPLEX, 0.40, lcol, 1, cv2.LINE_AA)
        fill = int(w * vis_score)
        cv2.rectangle(frame, (0, h - 2), (w, h), (10, 18, 28), -1)
        if fill > 0:
            cv2.rectangle(frame, (0, h - 2), (fill, h), lcol, -1)
        return frame


def _encode_frame(frame: np.ndarray) -> str:
    _, buf = cv2.imencode(".jpg", frame, [cv2.IMWRITE_JPEG_QUALITY, 72])
    return base64.b64encode(buf.tobytes()).decode()


