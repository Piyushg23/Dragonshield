@app.post("/api/process-frame")
async def process_video_frame(payload: dict):
    """
    Receive a base64 JPEG frame from the frontend (uploaded video or demo).
    Run MOG2 + Kalman detection. Return annotated frame + detections.
    Also feeds the result into the shared fusion engine so the dashboard updates.
    """
    try:
        b64 = payload.get("frame_b64", "")
        reset = payload.get("reset", False)

        img_bytes = base64.b64decode(b64)
        arr = np.frombuffer(img_bytes, dtype=np.uint8)
        frame = cv2.imdecode(arr, cv2.IMREAD_COLOR)
        if frame is None:
            return JSONResponse({"error": "Could not decode frame"}, status_code=400)

        with _upload_lock:
            proc = _get_upload_processor()
            if reset:
                proc.reset()
            result = proc.process(frame)

        # Push visual result into fusion so the dashboard telemetry reflects it
        if _FUSION and _VISUAL:
            vis_update = dict(_VISUAL.read()[0])   # get current vis state
            vis_update["score"]    = result["visual_score"]
            vis_update["n_tracks"] = result["n_tracks"]
            vis_update["tracks"]   = result["tracks"]
            # We can't easily inject this without rerunning fusion, so we
            # broadcast a lightweight video-detection event directly to clients
            if _clients:
                msg = json.dumps({
                    "type": "video_detection",
                    "visual_score": result["visual_score"],
                    "n_tracks": result["n_tracks"],
                    "tracks": result["tracks"],
                    "frame_b64": result["frame_b64"],
                    "fps": result["fps"],
                    "detector": result["detector"],
                }, default=str)
                asyncio.create_task(_broadcast(msg))

        return JSONResponse({
            "ok": True,
            "tracks": result["tracks"],
            "n_tracks": result["n_tracks"],
            "visual_score": result["visual_score"],
            "fps": result["fps"],
            "detector": result["detector"],
            "frame_b64": result["frame_b64"],
        })

    except Exception as e:
        log.error(f"process-frame error: {e}")
        return JSONResponse({"error": str(e)}, status_code=500)


@app.post("/api/reset-processor")
async def reset_processor():
    """Reset the upload video processor (call when loading a new video)."""
    with _upload_lock:
        proc = _get_upload_processor()
        proc.reset()
    return {"ok": True}


@app.post("/api/camera/start")
async def start_camera():
    """Start the webcam — only called when user explicitly clicks 'Open Webcam'."""
    if _VISUAL is None:
        return JSONResponse({"ok": False, "error": "Visual sensor not ready"}, status_code=503)
    success = _VISUAL.start_camera()
    return {"ok": success, "camera_active": _VISUAL.camera_active}


@app.post("/api/camera/stop")
async def stop_camera():
    """Stop the webcam."""
    if _VISUAL:
        _VISUAL.stop_camera()
    return {"ok": True, "camera_active": False}


@app.get("/api/camera/status")
async def camera_status():
    active = _VISUAL.camera_active if _VISUAL else False
    return {"camera_active": active}
