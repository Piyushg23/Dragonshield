import cv2

class KalmanTrack:
    """Constant-velocity Kalman filter for one drone track."""
    def __init__(self, cx, cy):
        self.x  = np.array([cx, cy, 0., 0.], dtype=np.float64)
        self.F  = np.array([[1,0,1,0],[0,1,0,1],[0,0,1,0],[0,0,0,1]], dtype=np.float64)
        self.H  = np.array([[1,0,0,0],[0,1,0,0]], dtype=np.float64)
        self.Q  = np.diag([1.,1.,4.,4.])
        self.R  = np.eye(2) * 4.
        self.P  = np.eye(4) * 10.

    def predict(self):
        self.x = self.F @ self.x
        self.P = self.F @ self.P @ self.F.T + self.Q

    def update(self, meas):
        z  = meas.reshape(2,1)
        y  = z - (self.H @ self.x).reshape(2,1)
        S  = self.H @ self.P @ self.H.T + self.R
        K  = self.P @ self.H.T @ np.linalg.inv(S)
        self.x = (self.x.reshape(4,1) + K @ y).flatten()
        self.P = (np.eye(4) - K @ self.H) @ self.P

    @property
    def pos(self): return float(self.x[0]), float(self.x[1])
    @property
    def vel(self): return float(self.x[2]), float(self.x[3])


class VisualSensor:
    """
    Real OpenCV camera capture + drone detection + Kalman tracking.
    Detection order of preference:
      1. YOLOv8 (if ultralytics installed)
      2. MOG2 background subtraction (works everywhere)
    Both paths feed the same Kalman multi-tracker.
    """

    def __init__(self, camera_index: int = 0):
        self.cap: Optional[cv2.VideoCapture] = None
        self.camera_active = False
        self._latest_frame: Optional[np.ndarray] = None
        self._latest_result: dict = {
            "score": 0.0, "n_tracks": 0, "fps": 0.0,
            "tracks": [], "camera_active": False, "detector": "none"
        }
        self._latest_annotated: Optional[np.ndarray] = None
        self._lock = threading.Lock()
        self._running = True

        # Detectors
        self.yolo = self._try_yolo()
        self.bg   = cv2.createBackgroundSubtractorMOG2(
            history=400, varThreshold=40, detectShadows=False)
        self.morph_k = cv2.getStructuringElement(cv2.MORPH_ELLIPSE, (5,5))

        # Multi-tracker state
        self._tracks: Dict[int, dict] = {}
        self._next_id = 0
        self._fps_times: deque = deque(maxlen=30)

        # DON'T auto-open camera — wait for explicit start_camera() call
        self._camera_index = camera_index
        self.camera_active = False

        # Start capture thread (runs headless until camera is started)
        t = threading.Thread(target=self._capture_loop, daemon=True)
        t.start()

    def _try_yolo(self):
        try:
            from ultralytics import YOLO
            model = YOLO("yolov8n.pt")
            log.info("✓ YOLOv8n loaded")
            return model
        except Exception:
            log.info("YOLOv8 not available — using MOG2 background subtraction")
            return None

    def _open_camera(self, idx: int) -> bool:
        cap = cv2.VideoCapture(idx)
        if cap.isOpened():
            cap.set(cv2.CAP_PROP_FRAME_WIDTH,  1280)
            cap.set(cv2.CAP_PROP_FRAME_HEIGHT,  720)
            cap.set(cv2.CAP_PROP_FPS,            30)
            cap.set(cv2.CAP_PROP_BUFFERSIZE,      2)
            self.cap = cap
            self.camera_active = True
            log.info(f"✓ Camera {idx} opened")
            return True
        else:
            log.warning(f"Camera {idx} not available")
            return False

    def start_camera(self) -> bool:
        """Explicitly start the webcam (called by API endpoint)."""
        if self.camera_active:
            return True
        return self._open_camera(self._camera_index)

    def stop_camera(self):
        """Stop the webcam and release resources."""
        self.camera_active = False
        if self.cap:
            self.cap.release()
            self.cap = None
        log.info("Camera stopped")

    def _capture_loop(self):
        frame_count = 0
        t_last = time.perf_counter()
        while self._running:
            if self.cap and self.camera_active:
                ret, frame = self.cap.read()
                if ret:
                    frame_count += 1
                    now = time.perf_counter()
                    if now - t_last >= 1.0:
                        fps = frame_count / (now - t_last)
                        frame_count = 0
                        t_last = now
                    else:
                        fps = None
                    result, annotated = self._process(frame, fps)
                    with self._lock:
                        self._latest_frame    = frame
                        self._latest_result   = result
                        self._latest_annotated = annotated
                    self._fps_times.append(time.perf_counter())
                else:
                    time.sleep(0.033)
            else:
                # No camera: still run detector on blank frame so
                # tracker state is maintained and score returns 0
                blank = np.zeros((480, 640, 3), dtype=np.uint8)
                result, annotated = self._process(blank, 0.0)
                with self._lock:
                    self._latest_result   = result
                    self._latest_annotated = annotated
                time.sleep(0.1)

    def _detect_mog2(self, frame: np.ndarray) -> List[dict]:
        fg = self.bg.apply(frame)
        fg = cv2.morphologyEx(fg, cv2.MORPH_OPEN, self.morph_k)
        fg = cv2.dilate(fg, self.morph_k, iterations=2)
        cnts, _ = cv2.findContours(fg, cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_SIMPLE)
        boxes = []
        for c in cnts:
            area = cv2.contourArea(c)
            if 150 < area < 80000:
                x, y, w, h = cv2.boundingRect(c)
                asp = w / max(h, 1)
                if 0.2 < asp < 5.0:
                    boxes.append({"x1": x, "y1": y, "x2": x+w, "y2": y+h,
                                  "cx": x+w/2, "cy": y+h/2,
                                  "w": w, "h": h,
                                  "conf": min(1.0, area/10000)})
        return boxes

    def _detect_yolo(self, frame: np.ndarray) -> List[dict]:
        results = self.yolo(frame, verbose=False, conf=0.30)
        boxes = []
        for r in results:
            for box in r.boxes:
                conf = float(box.conf[0])
                x1, y1, x2, y2 = [float(v) for v in box.xyxy[0]]
                w, h = x2-x1, y2-y1
                boxes.append({"x1": x1, "y1": y1, "x2": x2, "y2": y2,
                               "cx": (x1+x2)/2, "cy": (y1+y2)/2,
                               "w": w, "h": h, "conf": conf})
        return boxes

    def _update_tracks(self, detections: List[dict]) -> List[dict]:
        # Predict all existing Kalman filters
        for t in self._tracks.values():
            t["kf"].predict()

        # Greedy IoU/distance assignment
        tids = list(self._tracks.keys())
        matched_t, matched_d, used_t, used_d = {}, {}, set(), set()
        if tids and detections:
            cost = np.zeros((len(tids), len(detections)))
            for ti, tid in enumerate(tids):
                px, py = self._tracks[tid]["kf"].pos
                for di, d in enumerate(detections):
                    cost[ti, di] = math.hypot(px - d["cx"], py - d["cy"])
            flat = np.argsort(cost, axis=None)
            for idx in flat:
                ti, di = divmod(idx, len(detections))
                if ti in used_t or di in used_d: continue
                if cost[ti, di] > 120: break
                tid = tids[ti]
                matched_t[tid] = detections[di]
                used_t.add(ti); used_d.add(di)

        # Update matched
        for tid, det in matched_t.items():
            t = self._tracks[tid]
            t["kf"].update(np.array([det["cx"], det["cy"]]))
            t["box"] = det
            t["gone"] = 0
            t["frames"] += 1
            pos = t["kf"].pos
            t["traj"].append(pos)
            if len(t["traj"]) > 50: t["traj"].pop(0)

        # New tracks for unmatched detections
        for di, det in enumerate(detections):
            if di in used_d: continue
            nid = self._next_id; self._next_id += 1
            self._tracks[nid] = {
                "kf": KalmanTrack(det["cx"], det["cy"]),
                "box": det, "gone": 0, "frames": 1,
                "traj": [(det["cx"], det["cy"])],
            }

        # Age unmatched existing tracks
        for ti, tid in enumerate(tids):
            if ti not in used_t:
                self._tracks[tid]["gone"] += 1

        # Remove dead tracks
        self._tracks = {tid: t for tid, t in self._tracks.items() if t["gone"] <= 20}

        # Build output
        out = []
        fh, fw = 480, 640  # defaults
        for tid, t in self._tracks.items():
            if t["gone"] > 0: continue
            pos = t["kf"].pos
            vel = t["kf"].vel
            box = t["box"]
            speed = math.hypot(*vel)
            heading = (math.degrees(math.atan2(vel[1], vel[0])) + 360) % 360
            # Rough distance estimate (0.3m drone, ~800px focal)
            dist_m = (0.3 * 800) / max(box["w"], 1)
            threat = min(1.0, (1.0/max(dist_m, 1))*10 + speed*0.03)
            out.append({
                "id":          tid,
                "x1":          int(box["x1"]), "y1": int(box["y1"]),
                "x2":          int(box["x2"]), "y2": int(box["y2"]),
                "cx":          round(pos[0], 1), "cy": round(pos[1], 1),
                "vx":          round(vel[0], 2), "vy": round(vel[1], 2),
                "heading":     round(heading, 1),
                "distance_m":  round(dist_m, 1),
                "confidence":  round(box["conf"], 3),
                "threat":      round(threat, 3),
                "frames":      t["frames"],
                "traj":        [[round(p[0],1), round(p[1],1)] for p in t["traj"]],
            })
        return out

    def _process(self, frame: np.ndarray, fps_override) -> Tuple[dict, np.ndarray]:
        # Detect
        if self.yolo and self.camera_active:
            try:
                detections = self._detect_yolo(frame)
                detector = "yolov8n"
            except Exception:
                detections = self._detect_mog2(frame)
                detector = "mog2"
        else:
            detections = self._detect_mog2(frame) if self.camera_active else []
            detector = "mog2"

        tracks = self._update_tracks(detections)

        fps = fps_override if fps_override is not None else (
            len(self._fps_times) / (
                (self._fps_times[-1] - self._fps_times[0]) + 1e-6
            ) if len(self._fps_times) > 1 else 0.0
        )

        vis_score = max((t["threat"] for t in tracks), default=0.0)
        result = {
            "score":          round(vis_score, 4),
            "n_tracks":       len(tracks),
            "fps":            round(float(fps), 1),
            "tracks":         tracks,
            "camera_active":  self.camera_active,
            "detector":       detector,
        }

        # Annotate frame
        annotated = self._annotate(frame.copy(), tracks, vis_score)
        return result, annotated

    def _annotate(self, frame: np.ndarray, tracks: List[dict], vis_score: float) -> np.ndarray:
        h, w = frame.shape[:2]

        def threat_bgr(s):
            if s < 0.35: return (159, 255,   0)
            if s < 0.60: return (255, 200,   0)
            if s < 0.80: return (0,  100, 255)
            return (0, 0, 255)

        for t in tracks:
            col = threat_bgr(t["threat"])
            x1, y1, x2, y2 = t["x1"], t["y1"], t["x2"], t["y2"]
            cx, cy = int(t["cx"]), int(t["cy"])
            bw = x2 - x1

            # Box glow
            cv2.rectangle(frame, (x1-1,y1-1), (x2+1,y2+1), col, 1)
            cv2.rectangle(frame, (x1, y1), (x2, y2), col, 2)

            # Corner ticks
            tk = min(14, bw//3)
            for ox,oy,dx,dy in [(x1,y1,tk,0),(x1,y1,0,tk),(x2,y1,-tk,0),(x2,y1,0,tk),
                                  (x1,y2,tk,0),(x1,y2,0,-tk),(x2,y2,-tk,0),(x2,y2,0,-tk)]:
                cv2.line(frame,(ox,oy),(ox+dx,oy+dy),col,2)

            # Centre cross
            cv2.line(frame,(cx-5,cy),(cx+5,cy),col,1)
            cv2.line(frame,(cx,cy-5),(cx,cy+5),col,1)

            # Trajectory
            traj = t["traj"]
            for i in range(1, len(traj)):
                alpha = i/len(traj)
                pt1 = (int(traj[i-1][0]), int(traj[i-1][1]))
                pt2 = (int(traj[i][0]),   int(traj[i][1]))
                fade = tuple(int(c*alpha*0.5) for c in col)
                cv2.line(frame, pt1, pt2, fade, 1)

            # Velocity arrow
            spd = math.hypot(t["vx"], t["vy"])
            if spd > 0.8:
                ang = math.atan2(t["vy"], t["vx"])
                r   = bw//2 + 12
                ax, ay = int(cx+math.cos(ang)*r), int(cy+math.sin(ang)*r)
                ex  = int(ax + math.cos(ang)*min(spd*10,50))
                ey  = int(ay + math.sin(ang)*min(spd*10,50))
                cv2.arrowedLine(frame,(ax,ay),(ex,ey),col,2,tipLength=0.35)

            # Threat arc
            arc_r = bw//2 + 18
            cv2.ellipse(frame,(cx,cy),(arc_r,arc_r),-90,0,int(t["threat"]*360),col,2)

            # Labels
            cv2.putText(frame, f"T-{t['id']}  {t['confidence']*100:.0f}%  ~{t['distance_m']:.0f}m",
                        (x1, y1-10), cv2.FONT_HERSHEY_SIMPLEX, 0.42, col, 1, cv2.LINE_AA)
            cv2.putText(frame, f"{t['heading']:.0f}deg  {t['threat']*100:.0f}% thr",
                        (x1, y1-1), cv2.FONT_HERSHEY_SIMPLEX, 0.35, col, 1, cv2.LINE_AA)

        # Level text
        if vis_score < 0.10:    lvl, col_text = "CLEAR",    (159,255,0)
        elif vis_score < 0.35:  lvl, col_text = "LOW",      (0,255,136)
        elif vis_score < 0.60:  lvl, col_text = "MEDIUM",   (0,200,255)
        elif vis_score < 0.80:  lvl, col_text = "HIGH",     (0,100,255)
        else:                   lvl, col_text = "CRITICAL", (0,0,255)

        # HUD bar
        ov = frame.copy()
        cv2.rectangle(ov,(0,0),(w,30),(5,12,20),-1)
        cv2.addWeighted(ov,0.75,frame,0.25,0,frame)
        cv2.putText(frame,f"DRAGONSHIELD [{lvl}]",
                    (10,21),cv2.FONT_HERSHEY_SIMPLEX,0.52,col_text,1,cv2.LINE_AA)
        score_txt = f"VIS {vis_score:.3f}"
        tw = cv2.getTextSize(score_txt,cv2.FONT_HERSHEY_SIMPLEX,0.45,1)[0][0]
        cv2.putText(frame,score_txt,(w//2-tw//2,21),
                    cv2.FONT_HERSHEY_SIMPLEX,0.45,col_text,1,cv2.LINE_AA)
        trk_txt = f"{len(tracks)} TRKS"
        tw2 = cv2.getTextSize(trk_txt,cv2.FONT_HERSHEY_SIMPLEX,0.40,1)[0][0]
        cv2.putText(frame,trk_txt,(w-tw2-10,21),
                    cv2.FONT_HERSHEY_SIMPLEX,0.40,(80,140,180),1,cv2.LINE_AA)

        # Bottom threat bar
        fill = int(w * vis_score)
        cv2.rectangle(frame,(0,h-5),(w,h),(15,25,35),-1)
        if fill > 0:
            cv2.rectangle(frame,(0,h-5),(fill,h),col_text,-1)

        # Alarm border flash
        if vis_score > 0.80 and int(time.time()*2)%2==0:
            cv2.rectangle(frame,(0,0),(w-1,h-1),(0,0,255),4)

        # Corner brackets
        L=22
        for ox,oy,sx,sy in [(0,0,1,1),(w,0,-1,1),(0,h,1,-1),(w,h,-1,-1)]:
            cv2.line(frame,(ox,oy),(ox+sx*L,oy),col_text,2)
            cv2.line(frame,(ox,oy),(ox,oy+sy*L),col_text,2)

        return frame

    def read(self) -> Tuple[dict, Optional[np.ndarray]]:
        with self._lock:
            return dict(self._latest_result), (
                self._latest_annotated.copy()
                if self._latest_annotated is not None else None
            )

    def stop(self):
        self._running = False
        if self.cap:
            self.cap.release()


